-- languard/domains.lua — 域名黑名单
--
-- 域名规则写不进 nft,所以落成一个 hosts 文件交给 dnsmasq 的 addnhosts 读取。
-- 刷新只发 HUP,不重启 dnsmasq——重启会打断 DHCP。

local jsonc = require "luci.jsonc"
local fs = require "nixio.fs"
local sys = require "luci.sys"

local M = {}

local D = {}
local MAX_DOMAINS = 20000

function M.setup(deps)
	D = deps
end

local function ok(t)
	t = t or {}
	t.success = true
	t.running = true
	return t
end

local function err(m) return { success = false, error = m } end

local function trim(s) return (s:gsub("^%s+", ""):gsub("%s+$", "")) end

-- ---------- 状态 ----------
function M.load()
	local d = D.load_json_map(D.domain_file, function()
		return { enabled = true, names = {} }
	end)
	d.names = type(d.names) == "table" and d.names or {}
	if d.enabled == nil then d.enabled = true end
	return d
end

function M.save(d)
	return D.save_json_map(D.domain_file, d)
end

-- 只接受主机名。带路径、通配符或纯数字末段的都拒掉,
-- 免得把正文和版本号写进名单。
function M.is_token(tok)
	if #tok < 4 or #tok > 253 then return false end
	if not tok:match("^[%w][%w%.%-]*$") then return false end
	if not tok:find(".", 1, true) then return false end
	if tok:match("^[%d%.]+$") then return false end
	local tld = tok:match("%.([%a]+)$")
	if not tld or #tld < 2 or #tld > 24 then return false end
	if tok:match("%.lan$") or tok:match("%.local$") or tok:match("%.arpa$")
		or tok:match("%.localhost$") then return false end
	return true
end

function M.render_hosts()
	local d = M.load()
	if not d.enabled then
		os.remove(D.hosts)
		return false
	end
	local f = io.open(D.hosts, "w")
	if not f then return false end
	f:write("# generated by languard - edits are lost on the next refresh\n")
	for name in pairs(d.names) do
		f:write("0.0.0.0 ", name, "\n")
		f:write(":: ", name, "\n")
	end
	f:close()
	-- rpcd 的 umask 很严,dnsmasq 以非特权身份跑,读不到权限过紧的文件
	sys.call("chmod 644 " .. D.hosts)
	return true
end

-- dnsmasq 只有在 addnhosts 里登记后才会读这个文件;只补一次,不是每次刷新
function M.ensure_entry()
	local listed = false
	local fh = io.popen("uci -q get dhcp.@dnsmasq[0].addnhosts 2>/dev/null", "r")
	if fh then
		for line in fh:lines() do
			if line:find(D.hosts, 1, true) then listed = true end
		end
		fh:close()
	end
	if listed then return false end
	sys.call(string.format(
		"uci add_list dhcp.@dnsmasq[0].addnhosts=%s && uci commit dhcp", D.hosts))
	return true
end

-- 只写 hosts 并 HUP。写 uci 条目属于启动期基础设施,放在 sync 里。
function M.apply()
	M.render_hosts()
	sys.call("kill -HUP $(pidof dnsmasq) 2>/dev/null")
end

-- 启动路径专用:确保登记,缺了就重启一次 dnsmasq(HUP 读不到新条目)
function M.ensure()
	M.render_hosts()
	if M.ensure_entry() then
		sys.call("/etc/init.d/dnsmasq restart >/dev/null 2>&1")
		return ok({ restarted = true })
	end
	sys.call("kill -HUP $(pidof dnsmasq) 2>/dev/null")
	return ok({ restarted = false })
end

local function dns_logging()
	return (trim(sys.exec("uci -q get dhcp.@dnsmasq[0].logqueries 2>/dev/null") or "") == "1")
end

-- ---------- 对外方法 ----------
function M.hits(limit)
	limit = tonumber(limit) or 50
	if not dns_logging() then
		return { success = true, running = true, enabled = false, hits = {}, count = 0 }
	end
	local blocked = M.load().names
	local hits = {}
	local fh = io.popen("logread 2>/dev/null | grep -F 'query[' | tail -n 4000", "r")
	if fh then
		for line in fh:lines() do
			local dom, ip = line:match("query%[%w+%]%s+(%S+)%s+from%s+(%d+%.%d+%.%d+%.%d+)")
			if dom and blocked[dom] then
				hits[#hits + 1] = { domain = dom, ip = ip }
			end
		end
		fh:close()
	end
	local out = {}
	for i = #hits, math.max(1, #hits - limit + 1), -1 do
		out[#out + 1] = hits[i]
	end
	return { success = true, running = true, enabled = true, hits = out, count = #hits }
end

function M.togglelog(on_)
	local on = (on_ ~= false and on_ ~= "0" and on_ ~= "false")
	sys.call(string.format("uci set dhcp.@dnsmasq[0].logqueries=%s; uci commit dhcp",
		on and "1" or "0"))
	sys.call("/etc/init.d/dnsmasq reload >/dev/null 2>&1")
	return ok({ enabled = on })
end

function M.list()
	local d = M.load()
	local names = {}
	for name, meta in pairs(d.names) do
		names[#names + 1] = { domain = name, since = meta.since, note = meta.note,
		                      source = meta.source or "manual", feed = meta.feed }
	end
	table.sort(names, function(a, b) return (a.since or 0) > (b.since or 0) end)
	local out = {}
	for i = 1, math.min(#names, 500) do out[i] = names[i] end
	return { success = true, running = true, enabled = d.enabled,
	         count = #names, domains = out, file = D.hosts }
end

function M.add(name)
	local norm = tostring(name or ""):lower():gsub("^%*?%.?", ""):gsub("%.$", "")
	if not M.is_token(norm) then return err("not a domain") end
	local d = M.load()
	if d.names[norm] then return ok({ domain = norm, duplicate = true }) end
	if #d.names >= MAX_DOMAINS then return err("domain list is full") end
	d.names[norm] = { since = os.time(), source = "manual" }
	M.save(d)
	M.apply()
	return ok({ domain = norm })
end

function M.del(name)
	local norm = tostring(name or ""):lower()
	local d = M.load()
	if not d.names[norm] then return err("not in the list") end
	d.names[norm] = nil
	M.save(d)
	M.apply()
	return ok({})
end

function M.toggle(on_)
	local d = M.load()
	d.enabled = not (on_ == false or on_ == "0" or on_ == "false")
	M.save(d)
	M.apply()
	return ok({ enabled = d.enabled })
end

return M
