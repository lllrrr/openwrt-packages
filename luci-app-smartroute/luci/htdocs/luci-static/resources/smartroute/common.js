const RE = {
	mac: /^([0-9a-f]{2}[:-]){5}[0-9a-f]{2}$/i,
	v4: /^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}(\/(3[0-2]|[12]?\d))?$/,
	v6: /^[0-9a-f:.]*:[0-9a-f:.]*(\/(12[0-8]|1[01]\d|[1-9]?\d))?$/i
};

function addrKind(a) {
	return RE.mac.test(a) ? 'mac' : (RE.v4.test(a) || RE.v6.test(a)) ? 'ip' : null;
}

// xray rule line check: ok supported; warn supported with a difference; skip unsupported; bad malformed
function lint(line, cats) {
	const l = line.trim();
	let m = l.match(/^(geosite|geoip):([^@\s]+)(@!?[\w-]+)?$/i);
	if (m) {
		const list = cats && cats[m[1].toLowerCase()];
		if (list && list.length && list.indexOf(m[2].toLowerCase()) < 0)
			return { k: 'bad', msg: _('category not in the data file') };
		return { k: 'ok' };
	}
	if (/^domain:([a-z0-9-]+\.)*[a-z0-9-]+$/i.test(l)) return { k: 'ok' };
	if (/^full:([a-z0-9-]+\.)*[a-z0-9-]+$/i.test(l)) return { k: 'warn', msg: _('treated as domain:') };
	if (/^ext:[\w.-]+:[\w!@-]+$/i.test(l)) return { k: 'ok' };
	if (/^(keyword|regexp|dotless):/i.test(l)) return { k: 'skip', msg: _('not supported on the router, skipped') };
	if (addrKind(l) == 'ip') return { k: 'ok' };
	if (/^[\w.-]+$/.test(l)) return { k: 'skip', msg: _('without a prefix it means keyword:, skipped') };
	return { k: 'bad', msg: _('not recognised') };
}

